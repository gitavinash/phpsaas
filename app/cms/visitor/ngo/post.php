          <p
            class="lead"
            style="font-size: 1.25rem; font-weight: 500; color: #444"
          >
            In the heart of Kanpur's rural belt, a quiet revolution is taking
            place. It's not led by politicians or celebrities, but by ordinary
            women armed with sewing machines and a determination to change their
            destiny.
          </p>

          <p>
            For decades, women in these villages were confined to domestic
            chores, their economic potential untapped. However, with the launch
            of DPJKS's "Nari Shakti" Skill Development Program, the narrative is
            shifting rapidly.
          </p>

          <h3>The Beginning of Change</h3>
          <p>
            When we first visited Village Bilhaur, we found that 80% of women
            were eager to work but lacked the skills. The desire for financial
            independence was palpable. We started with a simple pilot project: a
            sewing center with 10 machines.
          </p>

          <img
            src="assets/images/gallery/education/1000071269.jpg"
            alt="Training Center"
            style="width: 100%; border-radius: 8px; margin: 1.5rem 0"
          />

          <blockquote>
            "I had never stepped out of my house for work. Today, I earn Rs.
            5,000 a month and pay for my daughter's tuition. DPJKS didn't just
            give me a skill; they gave me respect."
            <br /><span
              style="
                font-size: 0.9rem;
                font-weight: 600;
                margin-top: 0.5rem;
                display: block;
              "
              >— Geeta Devi, Program Beneficiary</span
            >
          </blockquote>

          <h3>Impact Beyond Income</h3>
          <p>
            The impact of this program goes beyond just numbers. Financial
            independence has led to increased decision-making power within
            households. Women are now prioritizing their children's education
            and better healthcare for their families.
          </p>
          <p>
            Today, over 500 women have graduated from our centers. Many have
            started their own micro-enterprises, while others have found
            employment in textile units in Kanpur city.
          </p>

          <h3>Future Goals</h3>
          <p>
            Our goal for 2026 is to expand this initiative to 20 more villages.
            We are also introducing digital literacy courses to help these women
            market their products online. With your support, we can turn this
            ripple of change into a wave of progress.
          </p>
        </div>

