                        their platform</li>
                </ul>
                <h3>Payment Data Collected by Cartt</h3>
                <ul>
                    <li><strong>Transaction Metadata:</strong> We collect and store transaction ID, payment amount,
                        currency, timestamp, and payment status for billing, invoicing, and accounting purposes</li>
                    <li><strong>Billing Information:</strong> We maintain records of your billing address, invoice
                        details, and order summaries for tax compliance and customer service</li>
                    <li><strong>Payment Method Type:</strong> We record only the type of payment method used (e.g.,
                        "Credit Card," "UPI," "Net Banking") without storing actual payment credentials</li>
                    <li><strong>Subscription Details:</strong> For recurring payments, we maintain your subscription
                        plan information, billing cycle, and renewal dates</li>
                </ul>
                <h3>Razorpay Integration</h3>
                <ul>
                    <li><strong>PCI-DSS Compliance:</strong> Razorpay is certified as PCI-DSS Level 1 compliant, meeting
                        the highest international standards for payment card data security</li>
                    <li><strong>Tokenization:</strong> Razorpay may use tokenization to securely store payment
                        information on your behalf if you opt for saved payment methods. Cartt does not have access to
                        these tokens</li>
                    <li><strong>Payment Status Webhooks:</strong> Cartt receives payment status notifications from
                        Razorpay (success, failure, pending) to update your account and process orders accordingly</li>
                    <li><strong>Razorpay Privacy Policy:</strong> Your payment data processed by Razorpay is governed by
                        their privacy policy. We encourage you to review Razorpay's privacy and security practices at
                        https://razorpay.com/privacy</li>
                </ul>
                <h3>Payment Security Measures</h3>
                <ul>
                    <li><strong>Secure Transmission:</strong> All payment transactions are encrypted using SSL/TLS
                        protocols (HTTPS) to prevent unauthorized interception or access</li>
                    <li><strong>No Sensitive Data Logging:</strong> Cartt does not log, cache, or retain sensitive
                        payment information in our systems or databases</li>
                    <li><strong>Fraud Detection:</strong> Razorpay implements advanced fraud detection mechanisms to
                        identify and prevent unauthorized transactions and suspicious activities</li>
                    <li><strong>Secure Checkout:</strong> The payment checkout interface is hosted securely by Razorpay,
                        isolating payment processing from Cartt's infrastructure</li>
                </ul>
                <h3>Billing and Invoicing</h3>
                <ul>
                    <li><strong>Invoice Generation:</strong> Upon successful payment, Cartt generates invoices
                        containing transaction details, plan information, and billing address</li>
                    <li><strong>Invoice Storage:</strong> Invoices are retained in your account for record-keeping, tax
                        compliance, and financial reporting purposes</li>
                    <li><strong>Invoice Access:</strong> You can download and access all invoices related to your
                        account at any time through your Cartt dashboard</li>
                    <li><strong>Tax Information:</strong> If applicable, invoices include GST and other tax details as
                        per your business registration information</li>
                </ul>
                <h3>Refunds and Chargebacks</h3>
                <ul>
                    <li><strong>Refund Processing:</strong> All refunds are processed back to the original payment
                        method used for the transaction through Razorpay</li>
                    <li><strong>Refund Timeline:</strong> Refunds are typically processed within 5-7 business days,
                        though your bank may take additional time to credit the amount</li>
                    <li><strong>Chargeback Resolution:</strong> In case of disputed transactions or chargebacks, Cartt
                        will work with Razorpay to resolve the matter in accordance with card network rules and RBI
                        guidelines</li>
                </ul>
                <h3>Data Sharing with Payment Partner</h3>
                <ul>
                    <li><strong>Information Shared:</strong> To process payments, Cartt shares your name, email address,
                        phone number, billing address, and order details with Razorpay</li>
                    <li><strong>Contractual Obligation:</strong> This information sharing is necessary to complete
                        payment transactions and is covered under Cartt's Data Processing Agreement with Razorpay</li>
                    <li><strong>Razorpay Liability:</strong> Razorpay handles your payment data as a payment processor
                        and is bound by their own privacy policy and applicable data protection laws</li>
                </ul>
                <h3>Recurring Payments and Subscriptions</h3>
                <ul>
                    <li><strong>Auto-Renewal:</strong> If you subscribe to a recurring plan, Cartt (via Razorpay) will
                        automatically charge your selected payment method on each billing cycle</li>
                    <li><strong>Subscription Management:</strong> You can manage your subscription, update payment
                        methods, or cancel subscriptions from your account dashboard</li>
